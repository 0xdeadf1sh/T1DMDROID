        let side = state
            .wrapping_mul(side_mul)
            .wrapping_add(folded7.wrapping_mul(side_folded_mul))
            .wrapping_add(side_add);
        let folded8 = fold32_by_nibbles_63c278(folded7, fold_table, 1, t)?;
